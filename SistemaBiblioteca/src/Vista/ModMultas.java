    private void cargarTablaMultas() {
    DefaultTableModel modelo = (DefaultTableModel) tableMultas.getModel();
    modelo.setRowCount(0);

    for (Multa m : multaDao.listarMultas()) {
        modelo.addRow(new Object[]{
            m.getId_multa(),
            m.getId_prestamo(),
            m.getId_usuario(),
            m.getNombreUsuario(),
            m.getNombreLibro(),
            m.getDias_retraso(),
            m.getMonto(),
            m.getEstado()
        });
    }
}

   

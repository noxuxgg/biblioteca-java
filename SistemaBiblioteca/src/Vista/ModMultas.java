    private void btnmodifcarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnmodifcarActionPerformed
      try {
        if (Txt_diasretraso.getText().trim().isEmpty() || Txt_monto.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Ingrese días de retraso y monto.", 
                    "Validación", JOptionPane.WARNING_MESSAGE);
            return;
        }

        int dias = Integer.parseInt(Txt_diasretraso.getText().trim());
        float monto = Float.parseFloat(Txt_monto.getText().trim());

        Object sel = ComboBoxEstadomulta.getSelectedItem();
        if (sel == null || sel.toString().equals("Selecciona")) {
            JOptionPane.showMessageDialog(this, "Seleccione un estado válido.", 
                    "Validación", JOptionPane.WARNING_MESSAGE);
            return;
        }

        String estado = sel.toString();

        // Actualizar objeto multa
        multaRecibida.setDias_retraso(dias);
        multaRecibida.setMonto(monto);
        multaRecibida.setEstado(estado);

        boolean ok = multaDao.modificarMulta(multaRecibida);

        if (ok) {
            JOptionPane.showMessageDialog(this, 
                    "Multa actualizada correctamente.");

            // Refrescar ventana principal
            if (parent != null) {
                parent.listarTodasLasMultas(); 
                parent.listarMultasPagadas();
                parent.listarMultasSinPagar();
            }

            this.dispose();
            cargarTablaMultas();
        } else {
            JOptionPane.showMessageDialog(this, "Error al actualizar la multa.", 
                    "Error", JOptionPane.ERROR_MESSAGE);
        }

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Días y monto deben ser numéricos.",
                "Error formato", JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_btnmodifcarActionPerformed

